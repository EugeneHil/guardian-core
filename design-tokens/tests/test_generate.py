from __future__ import annotations

import copy
import importlib.util
import json
import os
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

_spec = importlib.util.spec_from_file_location("generate", os.path.join(ROOT, "generate.py"))
generate = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(generate)

FIXTURE = {
    "color": {
        "background": {"light": "#FFFFFF", "dark": "#1C1C1E"},
        "textSecondary": {"light": "#6E6E73", "dark": "#98989D"},
    },
    "typography": {"body": {"size": 13, "weight": 400}},
    "spacing": {"md": 12},
    "radius": {"lg": 14},
}


def load_dict(data):
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "tokens.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(data, fh)
        return generate.load_tokens(path)


class RenderCssTests(unittest.TestCase):
    def test_css_has_light_root_and_dark_media_block(self):
        css = generate.render_css(FIXTURE)
        self.assertTrue(css.startswith(
            "/* Generated by design-tokens/generate.py from tokens.json — do not edit. */\n"))
        self.assertIn(":root {\n  --color-background: #FFFFFF;", css)
        self.assertIn("@media (prefers-color-scheme: dark) {\n  :root {\n    --color-background: #1C1C1E;", css)
        dark = css.split("@media")[1]
        self.assertNotIn("--space-md", dark)
        self.assertNotIn("--font-body-size", dark)
        self.assertTrue(css.endswith("}\n"))
        self.assertFalse(css.endswith("\n\n"))

    def test_css_names_are_kebab_case_with_group_prefix(self):
        css = generate.render_css(FIXTURE)
        for line in (
            "--color-text-secondary: #6E6E73;",
            "--font-body-size: 13px;",
            "--font-body-weight: 400;",
            "--space-md: 12px;",
            "--radius-lg: 14px;",
        ):
            self.assertIn(line, css)

    def test_css_is_deterministic(self):
        self.assertEqual(generate.render_css(FIXTURE), generate.render_css(copy.deepcopy(FIXTURE)))


class LoadTokensTests(unittest.TestCase):
    def test_load_rejects_bad_hex(self):
        data = copy.deepcopy(FIXTURE)
        data["color"]["background"]["light"] = "#GGGGGG"
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("color.background.light", str(ctx.exception))
        self.assertIn("#GGGGGG", str(ctx.exception))

    def test_load_rejects_non_camel_case_name(self):
        data = copy.deepcopy(FIXTURE)
        data["spacing"]["Big_one"] = 5
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("spacing.Big_one", str(ctx.exception))

    def test_load_rejects_missing_group(self):
        data = copy.deepcopy(FIXTURE)
        del data["radius"]
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("radius", str(ctx.exception))

    def test_load_rejects_unknown_group(self):
        data = copy.deepcopy(FIXTURE)
        data["shadow"] = {}
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("shadow", str(ctx.exception))

    def test_load_rejects_missing_dark(self):
        data = copy.deepcopy(FIXTURE)
        del data["color"]["background"]["dark"]
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("color.background.dark", str(ctx.exception))

    def test_load_rejects_non_positive_number(self):
        data = copy.deepcopy(FIXTURE)
        data["spacing"]["md"] = 0
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("spacing.md", str(ctx.exception))
        data = copy.deepcopy(FIXTURE)
        data["typography"]["body"]["size"] = -1
        with self.assertRaises(ValueError) as ctx:
            load_dict(data)
        self.assertIn("typography.body.size", str(ctx.exception))

    def test_real_tokens_json_loads(self):
        tokens = generate.load_tokens(os.path.join(ROOT, "tokens.json"))
        self.assertEqual(tokens["color"]["textSecondary"]["light"], "#6E6E73")


class MainTests(unittest.TestCase):
    def _tokens_file(self, tmp):
        path = os.path.join(tmp, "tokens.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(FIXTURE, fh)
        return path

    def test_main_writes_css(self):
        with tempfile.TemporaryDirectory() as tmp:
            css = os.path.join(tmp, "out.css")
            rc = generate.main(["--tokens", self._tokens_file(tmp), "--css", css,
                                "--swift", os.path.join(tmp, "T.swift")])
            self.assertEqual(rc, 0)
            with open(css, encoding="utf-8") as fh:
                self.assertEqual(fh.read(), generate.render_css(FIXTURE))

    def test_check_writes_nothing_and_flags_missing(self):
        with tempfile.TemporaryDirectory() as tmp:
            css = os.path.join(tmp, "out.css")
            rc = generate.main(["--tokens", self._tokens_file(tmp), "--css", css,
                                "--swift", os.path.join(tmp, "T.swift"), "--check"])
            self.assertEqual(rc, 1)
            self.assertFalse(os.path.exists(css))

    def test_check_passes_when_files_are_current(self):
        with tempfile.TemporaryDirectory() as tmp:
            css = os.path.join(tmp, "out.css")
            swift = os.path.join(tmp, "T.swift")
            tok = self._tokens_file(tmp)
            self.assertEqual(generate.main(["--tokens", tok, "--css", css, "--swift", swift]), 0)
            with open(swift, encoding="utf-8") as fh:
                self.assertEqual(fh.read(), generate.render_swift(FIXTURE))
            self.assertEqual(
                generate.main(["--tokens", tok, "--css", css, "--swift", swift, "--check"]), 0)

    def test_check_fails_when_a_file_is_stale(self):
        with tempfile.TemporaryDirectory() as tmp:
            css = os.path.join(tmp, "out.css")
            swift = os.path.join(tmp, "T.swift")
            tok = self._tokens_file(tmp)
            generate.main(["--tokens", tok, "--css", css, "--swift", swift])
            with open(swift, "a", encoding="utf-8") as fh:
                fh.write("// edited\n")
            with open(swift, encoding="utf-8") as fh:
                before = fh.read()
            self.assertEqual(
                generate.main(["--tokens", tok, "--css", css, "--swift", swift, "--check"]), 1)
            with open(swift, encoding="utf-8") as fh:
                self.assertEqual(fh.read(), before)

    def test_check_fails_when_swift_is_missing(self):
        with tempfile.TemporaryDirectory() as tmp:
            css = os.path.join(tmp, "out.css")
            swift = os.path.join(tmp, "T.swift")
            tok = self._tokens_file(tmp)
            with open(css, "w", encoding="utf-8") as fh:
                fh.write(generate.render_css(FIXTURE))
            self.assertEqual(
                generate.main(["--tokens", tok, "--css", css, "--swift", swift, "--check"]), 1)
            self.assertFalse(os.path.exists(swift))


class RenderSwiftTests(unittest.TestCase):
    def test_swift_declares_each_color_with_light_and_dark_hex(self):
        swift = generate.render_swift(FIXTURE)
        self.assertIn("static let textSecondary = Color(light: 0x6E6E73, dark: 0x98989D)", swift)
        self.assertIn("static let background = Color(light: 0xFFFFFF, dark: 0x1C1C1E)", swift)

    def test_swift_has_header_imports_and_namespaces(self):
        swift = generate.render_swift(FIXTURE)
        self.assertTrue(swift.startswith(
            "// Generated by design-tokens/generate.py from tokens.json — do not edit.\n"))
        for needle in ("import SwiftUI", "import AppKit", "enum Tokens {", "enum Palette {",
                       "enum Typography {", "enum Spacing {", "enum Radius {",
                       "appearance.bestMatch(from: [.darkAqua, .aqua])"):
            self.assertIn(needle, swift)
        self.assertTrue(swift.endswith("}\n"))
        self.assertFalse(swift.endswith("\n\n"))

    def test_swift_spacing_and_radius_are_cgfloat(self):
        swift = generate.render_swift(FIXTURE)
        self.assertIn("static let md: CGFloat = 12", swift)
        self.assertIn("static let lg: CGFloat = 14", swift)

    def test_swift_weights_map_to_font_weights(self):
        data = copy.deepcopy(FIXTURE)
        data["typography"] = {
            "title": {"size": 15, "weight": 600},
            "body": {"size": 13, "weight": 400},
            "label": {"size": 12, "weight": 500},
            "heavy": {"size": 20, "weight": 900},
            "thin": {"size": 10, "weight": 100},
            "mono": {"size": 12, "weight": 400},
        }
        swift = generate.render_swift(data)
        self.assertIn("static let title = Font.system(size: 15, weight: .semibold)", swift)
        self.assertIn("static let body = Font.system(size: 13, weight: .regular)", swift)
        self.assertIn("static let label = Font.system(size: 12, weight: .medium)", swift)
        self.assertIn("static let heavy = Font.system(size: 20, weight: .bold)", swift)
        self.assertIn("static let thin = Font.system(size: 10, weight: .regular)", swift)
        self.assertIn(
            "static let mono = Font.system(size: 12, weight: .regular, design: .monospaced)", swift)

    def test_swift_is_deterministic(self):
        self.assertEqual(generate.render_swift(FIXTURE),
                         generate.render_swift(copy.deepcopy(FIXTURE)))

    def test_lowercase_hex_is_normalised_to_uppercase_in_both_outputs(self):
        data = copy.deepcopy(FIXTURE)
        data["color"]["background"]["light"] = "#ffaa0b"
        tokens = load_dict(data)
        self.assertEqual(tokens["color"]["background"]["light"], "#FFAA0B")
        self.assertIn("Color(light: 0xFFAA0B,", generate.render_swift(tokens))
        self.assertIn("--color-background: #FFAA0B;", generate.render_css(tokens))


if __name__ == "__main__":
    unittest.main()
