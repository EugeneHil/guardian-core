"""Generate platform artifacts (CSS, later Swift) from tokens.json."""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import Dict, List, Optional

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TOKENS = os.path.join(HERE, "tokens.json")
DEFAULT_CSS = os.path.join(HERE, "generated", "tokens.css")
DEFAULT_SWIFT = os.path.join(HERE, "generated", "Tokens.swift")

GROUPS = ("color", "typography", "spacing", "radius")
NAME_RE = re.compile(r"^[a-z][a-zA-Z0-9]*$")
HEX_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
HEADER = "/* Generated by design-tokens/generate.py from tokens.json — do not edit. */"


def _is_pos_int(value: object) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


def _check_int(value: object, path: str) -> None:
    if not _is_pos_int(value):
        raise ValueError("%s: expected positive integer, got %r" % (path, value))


def _check_object(value: object, path: str) -> Dict[str, object]:
    if not isinstance(value, dict):
        raise ValueError("%s: expected object" % path)
    return value


def _check_exact_keys(obj: Dict[str, object], keys: List[str], path: str) -> None:
    for key in keys:
        if key not in obj:
            raise ValueError("%s.%s: missing" % (path, key))
    for key in obj:
        if key not in keys:
            raise ValueError("%s.%s: unknown key" % (path, key))


def load_tokens(path: str) -> dict:
    with open(path, "r", encoding="utf-8") as fh:
        try:
            data = json.load(fh)
        except json.JSONDecodeError as exc:
            raise ValueError("%s: invalid JSON: %s" % (path, exc))
    root = _check_object(data, "$")
    for group in GROUPS:
        if group not in root:
            raise ValueError("%s: missing group" % group)
    for group in root:
        if group not in GROUPS:
            raise ValueError("%s: unknown group" % group)
    for group in GROUPS:
        entries = _check_object(root[group], group)
        for name, value in entries.items():
            where = "%s.%s" % (group, name)
            if not NAME_RE.match(name):
                raise ValueError("%s: name is not lowerCamelCase" % where)
            if group == "color":
                color = _check_object(value, where)
                _check_exact_keys(color, ["light", "dark"], where)
                for mode in ("light", "dark"):
                    hex_value = color[mode]
                    if not isinstance(hex_value, str) or not HEX_RE.match(hex_value):
                        raise ValueError("%s.%s: invalid hex %r" % (where, mode, hex_value))
            elif group == "typography":
                typo = _check_object(value, where)
                _check_exact_keys(typo, ["size", "weight"], where)
                _check_int(typo["size"], where + ".size")
                _check_int(typo["weight"], where + ".weight")
            else:
                _check_int(value, where)
    return root


def _kebab(name: str) -> str:
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), name)


def _declarations(tokens: dict, mode: Optional[str]) -> List[str]:
    """Light pass (mode='light') emits everything; dark pass emits colors only."""
    lines = []  # type: List[str]
    for name, value in tokens["color"].items():
        lines.append("--color-%s: %s;" % (_kebab(name), value[mode or "light"]))
    if mode == "dark":
        return lines
    for name, value in tokens["typography"].items():
        lines.append("--font-%s-size: %dpx;" % (_kebab(name), value["size"]))
        lines.append("--font-%s-weight: %d;" % (_kebab(name), value["weight"]))
    for name, value in tokens["spacing"].items():
        lines.append("--space-%s: %dpx;" % (_kebab(name), value))
    for name, value in tokens["radius"].items():
        lines.append("--radius-%s: %dpx;" % (_kebab(name), value))
    return lines


def render_css(tokens: dict) -> str:
    out = [HEADER, ":root {"]
    out += ["  " + line for line in _declarations(tokens, "light")]
    out += ["}", "", "@media (prefers-color-scheme: dark) {", "  :root {"]
    out += ["    " + line for line in _declarations(tokens, "dark")]
    out += ["  }", "}"]
    return "\n".join(out) + "\n"


def _read(path: str) -> Optional[str]:
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(prog="generate.py")
    parser.add_argument("--tokens", default=DEFAULT_TOKENS)
    parser.add_argument("--css", default=DEFAULT_CSS)
    parser.add_argument("--swift", default=None)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    try:
        tokens = load_tokens(args.tokens)
    except (ValueError, OSError) as exc:
        sys.stderr.write("error: %s\n" % exc)
        return 2

    if args.check:
        stale = []  # type: List[str]
        if _read(args.css) != render_css(tokens):
            stale.append(args.css)
        # Swift output arrives with Task 11; until then the file counts as missing.
        swift_path = args.swift or DEFAULT_SWIFT
        if _read(swift_path) is None:
            stale.append(swift_path)
        for path in stale:
            sys.stderr.write("stale or missing: %s\n" % path)
        return 1 if stale else 0

    if args.swift is not None:
        sys.stderr.write("error: not implemented\n")
        return 2

    os.makedirs(os.path.dirname(os.path.abspath(args.css)), exist_ok=True)
    with open(args.css, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_css(tokens))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
